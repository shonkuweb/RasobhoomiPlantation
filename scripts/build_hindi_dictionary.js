async function matchAndBuild() {
    try {
        const res = await fetch('https://rasobhoomiplantation.com/api/products');
        if (!res.ok) throw new Error('HTTP Error: ' + res.status);
        const data = await res.json();
        const prods = Array.isArray(data) ? data : (data.products || []);
        console.log('Fetched live products count:', prods.length);

        const dict = {};
        prods.forEach((p, i) => {
            if (i < hindiNames.length) {
                dict[p.id] = {
                    enName: p.name,
                    hiName: hindiNames[i]
                };
            }
        });

        fs.writeFileSync(path.join(__dirname, '../src/utils/hindi_products_map.json'), JSON.stringify(dict, null, 2));
        console.log('Saved hindi_products_map.json successfully!');
    } catch (e) {
        console.error(e.message);
    }
}

matchAndBuild();
