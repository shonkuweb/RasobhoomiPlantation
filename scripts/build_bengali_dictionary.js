async function matchAndBuild() {
    try {
        const res = await fetch('https://rasobhoomiplantation.com/api/products');
        if (!res.ok) throw new Error('HTTP Error: ' + res.status);
        const data = await res.json();
        const prods = Array.isArray(data) ? data : (data.products || []);
        console.log('Fetched live products count:', prods.length);

        const hindiMap = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/utils/hindi_products_map.json'), 'utf-8'));
        
        prods.forEach((p, i) => {
            if (i < bnNames.length && hindiMap[p.id]) {
                hindiMap[p.id].bnName = bnNames[i];
            }
        });

        fs.writeFileSync(path.join(__dirname, '../src/utils/hindi_bengali_products_map.json'), JSON.stringify(hindiMap, null, 2));
        console.log('Saved hindi_bengali_products_map.json successfully!');
    } catch (e) {
        console.error(e.message);
    }
}

