/**
 * Helper function to translate a UI key string.
 */
export const t = (key, lang = 'en') => {
    const activeLang = uiTranslations[lang] ? lang : 'en';
    return uiTranslations[activeLang][key] || uiTranslations['en'][key] || key;
};

/**
 * Helper function to translate product fields dynamically without altering original data structure.
 */
export const translateProduct = (product, lang = 'en') => {
    if (!product) return product;
    if (lang === 'en') return product;

    // Check by ID first
    if (product.id && productTranslations[product.id]) {
        const trans = productTranslations[product.id];
        return {
            ...product,
            name: (trans.name && trans.name[lang]) || product.name,
            description: (trans.description && trans.description[lang]) || product.description,
            category: (trans.category && trans.category[lang]) || translateCategoryName(product.category, lang),
        };
    }

    // Dynamic category translation fallback
    let translatedCategory = translateCategoryName(product.category, lang);

    // Simple common word replacement fallback for demo / newly added products
    let translatedName = product.name || '';
    let translatedDesc = product.description || '';

    if (lang === 'hi') {
        translatedName = translatedName
            .replace(/\bMango Plant\b/gi, "आम का पौधा")
            .replace(/\bMango Sapling\b/gi, "आम का पौधा")
            .replace(/\bMango Tree\b/gi, "आम का पेड़")
            .replace(/\bMango\b/gi, "आम")
            .replace(/\bGuava Plant\b/gi, "अमरूद का पौधा")
            .replace(/\bGuava\b/gi, "अमरूद")
            .replace(/\bLemon Plant\b/gi, "नींबू का पौधा")
            .replace(/\bLemon\b/gi, "नींबू")
            .replace(/\bJackfruit\b/gi, "कटहल")
            .replace(/\bOrange\b/gi, "संतरा")
            .replace(/\bCoconut\b/gi, "नारियल")
            .replace(/\bLitchi\b/gi, "लीची")
            .replace(/\bGrafted\b/gi, "कलमी")
            .replace(/\bHybrid\b/gi, "हाइब्रिड")
            .replace(/\bVariety\b/gi, "किस्म")
            .replace(/\bSapling\b/gi, "पौधा")
            .replace(/\bPlant\b/gi, "पौधा")
            .replace(/\bPlants\b/gi, "पौधे")
            .replace(/\bTree\b/gi, "पेड़")
            .replace(/\bTrees\b/gi, "पेड़")
            .replace(/\bSweet\b/gi, "मीठा")
            .replace(/\bRed\b/gi, "लाल")
            .replace(/\bGreen\b/gi, "हरा")
            .replace(/\bBlack\b/gi, "काला")
            .replace(/\bYellow\b/gi, "पीला")
            .replace(/\bPink\b/gi, "गुलाबी")
            .replace(/\bSeedless\b/gi, "बीज रहित")
            .replace(/\bAll Time\b/gi, "बारहमासी")
            .replace(/\btest2\b/gi, "परीक्षण २")
            .replace(/\btest\b/gi, "परीक्षण");
        
        translatedDesc = translatedDesc
            .replace(/this is test/gi, "यह एक परीक्षण विवरण है");
    } else if (lang === 'bn') {
        translatedName = translatedName
            .replace(/\bMango Plant\b/gi, "আম গাছ")
            .replace(/\bMango Sapling\b/gi, "আম গাছ")
            .replace(/\bMango Tree\b/gi, "আম গাছ")
            .replace(/\bMango\b/gi, "আম")
            .replace(/\bGuava Plant\b/gi, "পেয়ারা গাছ")
            .replace(/\bGuava\b/gi, "পেয়ারা")
            .replace(/\bLemon Plant\b/gi, "লেবু গাছ")
            .replace(/\bLemon\b/gi, "লেবু")
            .replace(/\bJackfruit\b/gi, "কাঁঠাল")
            .replace(/\bOrange\b/gi, "কমলালেবু")
            .replace(/\bCoconut\b/gi, "নারকেল")
            .replace(/\bLitchi\b/gi, "লিচু")
            .replace(/\bGrafted\b/gi, "কলমি")
            .replace(/\bHybrid\b/gi, "হাইব্রিড")
            .replace(/\bVariety\b/gi, "জাত")
            .replace(/\bSapling\b/gi, "চারা")
            .replace(/\bPlant\b/gi, "গাছ")
            .replace(/\bPlants\b/gi, "গাছ")
            .replace(/\bTree\b/gi, "গাছ")
            .replace(/\bTrees\b/gi, "গাছ")
            .replace(/\bSweet\b/gi, "মিষ্টি")
            .replace(/\bRed\b/gi, "লাল")
            .replace(/\bGreen\b/gi, "সবুজ")
            .replace(/\bBlack\b/gi, "কালো")
            .replace(/\bYellow\b/gi, "হলুদ")
            .replace(/\bPink\b/gi, "গোলাপী")
            .replace(/\bSeedless\b/gi, "বীজহীন")
            .replace(/\bAll Time\b/gi, "বারোমাসি")
            .replace(/\btest2\b/gi, "পরীক্ষা ২")
            .replace(/\btest\b/gi, "পরীক্ষা");

        translatedDesc = translatedDesc
            .replace(/this is test/gi, "এটি একটি পরীক্ষামূলক বিবরণ");
    }

    return {
        ...product,
        name: translatedName,
        description: translatedDesc,
        category: translatedCategory
    };
};
